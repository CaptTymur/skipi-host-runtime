// emit.js — deterministic generator for the shared Skipi plugin host runtime.
//
// Single source of truth:   src/runtime.js  (verbatim, byte-identical to the
// runtime each home embeds — seeded from Seafarer's dist/plugin-host-bridge.js).
//
// Emits (all byte-derived from src/runtime.js, no transformation of the runtime):
//   dist/plugin-host-bridge.js   standalone <script src> form (file-based homes, e.g. Seafarer)
//                                -> BYTE-IDENTICAL to src/runtime.js.
//   dist/runtime.inline.html     marker-wrapped <script> block for single-file homes
//                                (On Board / Crewing inline it into dist/index.html).
//   dist/RUNTIME_VERSION         "<version>\nsha256:<hex>\n" — version + sha256 of the
//                                canonical standalone runtime bytes.
//
// Deterministic: no Date/random/network. Same src + same version -> same output bytes.
//
//   node tools/emit.js

import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC = path.join(ROOT, 'src', 'runtime.js');
const DIST = path.join(ROOT, 'dist');
const PKG = path.join(ROOT, 'package.json');

const version = JSON.parse(fs.readFileSync(PKG, 'utf8')).version;

// The runtime, exactly as written. This Buffer is the ONLY thing that becomes the
// canonical runtime; every emit derives from it without altering a byte of it.
const runtime = fs.readFileSync(SRC);
const sha256 = crypto.createHash('sha256').update(runtime).digest('hex');

fs.mkdirSync(DIST, { recursive: true });

// 1) standalone — verbatim copy (byte-for-byte identical to src/runtime.js).
const standalone = path.join(DIST, 'plugin-host-bridge.js');
fs.writeFileSync(standalone, runtime);

// 2) inline — same runtime bytes wrapped in a <script> + locator markers so a
//    single-file home's build can splice it into index.html between the markers.
//    The runtime body itself is untouched between the markers.
const BEGIN = '<!-- BEGIN skipi-host-runtime v' + version + ' sha256:' + sha256 + ' (generated by tools/emit.js from src/runtime.js — do not edit) -->';
const END = '<!-- END skipi-host-runtime -->';
const inline = Buffer.concat([
  Buffer.from(BEGIN + '\n<script>\n'),
  runtime,
  Buffer.from('\n</script>\n' + END + '\n'),
]);
fs.writeFileSync(path.join(DIST, 'runtime.inline.html'), inline);

// 3) version stamp — hashes the CANONICAL standalone runtime (the bytes a home runs).
fs.writeFileSync(path.join(DIST, 'RUNTIME_VERSION'), version + '\nsha256:' + sha256 + '\n');

console.log('skipi host-runtime emit OK');
console.log('  version : ' + version);
console.log('  sha256  : ' + sha256);
console.log('  bytes   : ' + runtime.length);
console.log('  ->', path.relative(ROOT, standalone), '(byte-identical to src/runtime.js)');
console.log('  ->', path.relative(ROOT, path.join(DIST, 'runtime.inline.html')));
console.log('  ->', path.relative(ROOT, path.join(DIST, 'RUNTIME_VERSION')));
